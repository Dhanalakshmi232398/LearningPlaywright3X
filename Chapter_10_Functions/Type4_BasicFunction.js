//Type 4- With parameter/argument and With return type

function sumOfTwoNumbers(a, b) {
    return a + b; // returns the sum of a and b
}

let c = sumOfTwoNumbers(2, 3); // returns c = 5
console.log(c); // Output: 5

console.log(sumOfTwoNumbers(5, 10)); // Output: 15, returns 15 but does not print anything